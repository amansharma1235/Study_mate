import 'package:flutter/material.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';
import 'package:google_fonts/google_fonts.dart';
import 'package:intl/intl.dart';

import '../../core/constants/app_colors.dart';
import '../../core/constants/app_dimensions.dart';
import '../../core/widgets/app_button.dart';
import '../../core/widgets/app_card.dart';
import '../../core/widgets/app_text_field.dart';
import '../../core/widgets/loading_skeleton.dart';
import '../../data/models/planner_model.dart';
import 'planner_controller.dart';

class PlannerScreen extends ConsumerStatefulWidget {
  const PlannerScreen({super.key});

  @override
  ConsumerState<PlannerScreen> createState() => _PlannerScreenState();
}

class _PlannerScreenState extends ConsumerState<PlannerScreen> {
  DateTime _selectedDate = DateTime.now();

  @override
  Widget build(BuildContext context) {
    final isDark = Theme.of(context).brightness == Brightness.dark;
    final sessionsAsync = ref.watch(plannerControllerProvider);

    return Scaffold(
      backgroundColor: isDark
          ? AppColors.backgroundDark
          : AppColors.backgroundLight,
      appBar: AppBar(
        title: Text(
          'Smart Study Planner',
          style: GoogleFonts.inter(fontWeight: FontWeight.w700),
        ),
        actions: [
          IconButton(
            icon: const Icon(
              Icons.auto_awesome_rounded,
              color: AppColors.primary,
            ),
            tooltip: 'Auto-Generate Schedule',
            onPressed: () => _showAutoGenerateDialog(context),
          ),
          IconButton(
            icon: const Icon(Icons.add_rounded),
            tooltip: 'Add Session',
            onPressed: () => _showAddSessionSheet(context),
          ),
        ],
      ),
      body: sessionsAsync.when(
        loading: () => const LoadingSkeletonList(count: 4),
        error: (err, _) => Center(child: Text('Error loading planner: $err')),
        data: (allSessions) {
          final daySessions = allSessions.where((s) {
            return s.sessionDate.year == _selectedDate.year &&
                s.sessionDate.month == _selectedDate.month &&
                s.sessionDate.day == _selectedDate.day;
          }).toList();

          // Check for conflicts
          final hasConflicts = _detectConflicts(daySessions);

          return Column(
            children: [
              // Horizontal Date Selector
              _buildDateStrip(isDark),

              // Conflict Alert Banner if any
              if (hasConflicts)
                Container(
                  margin: const EdgeInsets.symmetric(
                    horizontal: 16,
                    vertical: 8,
                  ),
                  padding: const EdgeInsets.symmetric(
                    horizontal: 14,
                    vertical: 10,
                  ),
                  decoration: BoxDecoration(
                    color: AppColors.error.withValues(alpha: 0.12),
                    borderRadius: BorderRadius.circular(10),
                    border: Border.all(
                      color: AppColors.error.withValues(alpha: 0.3),
                    ),
                  ),
                  child: Row(
                    children: [
                      const Icon(
                        Icons.warning_amber_rounded,
                        color: AppColors.error,
                        size: 22,
                      ),
                      const SizedBox(width: 10),
                      Expanded(
                        child: Text(
                          'Schedule Conflict Detected! Two or more sessions overlap on this day.',
                          style: TextStyle(
                            fontSize: 12.5,
                            fontWeight: FontWeight.w600,
                            color: isDark
                                ? const Color(0xFFFF8E8E)
                                : AppColors.error,
                          ),
                        ),
                      ),
                    ],
                  ),
                ),

              // Sessions List
              Expanded(
                child: daySessions.isEmpty
                    ? _buildEmptyState(isDark)
                    : ListView.builder(
                        padding: const EdgeInsets.all(AppDimensions.space16),
                        itemCount: daySessions.length,
                        itemBuilder: (context, idx) {
                          final session = daySessions[idx];
                          return _buildSessionCard(session, isDark);
                        },
                      ),
              ),
            ],
          );
        },
      ),
      floatingActionButton: FloatingActionButton.extended(
        backgroundColor: AppColors.primary,
        icon: const Icon(Icons.add_rounded, color: Colors.white),
        label: Text(
          'Add Session',
          style: GoogleFonts.inter(
            fontWeight: FontWeight.w700,
            color: Colors.white,
          ),
        ),
        onPressed: () => _showAddSessionSheet(context),
      ),
    );
  }

  bool _detectConflicts(List<StudySessionModel> sessions) {
    for (int i = 0; i < sessions.length; i++) {
      for (int j = i + 1; j < sessions.length; j++) {
        if (StudySessionModel.hasTimeConflict(sessions[i], sessions[j])) {
          return true;
        }
      }
    }
    return false;
  }

  Widget _buildDateStrip(bool isDark) {
    final now = DateTime.now();
    return Container(
      height: 82,
      padding: const EdgeInsets.symmetric(vertical: 8),
      decoration: BoxDecoration(
        color: isDark ? AppColors.surfaceDark : AppColors.surfaceLight,
        border: Border(
          bottom: BorderSide(
            color: isDark ? AppColors.borderDark : AppColors.borderLight,
          ),
        ),
      ),
      child: ListView.builder(
        scrollDirection: Axis.horizontal,
        padding: const EdgeInsets.symmetric(horizontal: 12),
        itemCount: 14,
        itemBuilder: (context, i) {
          final date = now.add(Duration(days: i - 2));
          final isSelected =
              date.year == _selectedDate.year &&
              date.month == _selectedDate.month &&
              date.day == _selectedDate.day;
          final isToday =
              date.year == now.year &&
              date.month == now.month &&
              date.day == now.day;

          return GestureDetector(
            onTap: () {
              setState(() {
                _selectedDate = date;
              });
            },
            child: AnimatedContainer(
              duration: const Duration(milliseconds: 200),
              width: 54,
              margin: const EdgeInsets.symmetric(horizontal: 4),
              decoration: BoxDecoration(
                color: isSelected
                    ? AppColors.primary
                    : (isDark ? AppColors.cardDark : Colors.white),
                borderRadius: BorderRadius.circular(12),
                border: Border.all(
                  color: isSelected
                      ? AppColors.primary
                      : (isToday
                            ? AppColors.primary.withValues(alpha: 0.5)
                            : Colors.transparent),
                  width: 1.5,
                ),
                boxShadow: isSelected
                    ? [
                        BoxShadow(
                          color: AppColors.primary.withValues(alpha: 0.3),
                          blurRadius: 6,
                          offset: const Offset(0, 3),
                        ),
                      ]
                    : null,
              ),
              child: Column(
                mainAxisAlignment: MainAxisAlignment.center,
                children: [
                  Text(
                    DateFormat('E').format(date).toUpperCase(),
                    style: TextStyle(
                      fontSize: 10,
                      fontWeight: FontWeight.w700,
                      color: isSelected
                          ? Colors.white.withValues(alpha: 0.8)
                          : AppColors.textSecondaryLight,
                    ),
                  ),
                  const SizedBox(height: 4),
                  Text(
                    date.day.toString(),
                    style: TextStyle(
                      fontSize: 16,
                      fontWeight: FontWeight.w800,
                      color: isSelected
                          ? Colors.white
                          : (isDark
                                ? Colors.white
                                : AppColors.textPrimaryLight),
                    ),
                  ),
                ],
              ),
            ),
          );
        },
      ),
    );
  }

  Widget _buildSessionCard(StudySessionModel session, bool isDark) {
    final priorityColor = _getPriorityColor(session.priority);

    return Dismissible(
      key: Key(session.id),
      direction: DismissDirection.endToStart,
      background: Container(
        alignment: Alignment.centerRight,
        padding: const EdgeInsets.only(right: 20),
        decoration: BoxDecoration(
          color: AppColors.error,
          borderRadius: BorderRadius.circular(12),
        ),
        child: const Icon(Icons.delete_outline_rounded, color: Colors.white),
      ),
      onDismissed: (_) {
        ref.read(plannerControllerProvider.notifier).deleteSession(session.id);
      },
      child: Container(
        margin: const EdgeInsets.only(bottom: 12),
        child: AppCard(
          padding: const EdgeInsets.all(14),
          child: Row(
            crossAxisAlignment: CrossAxisAlignment.start,
            children: [
              // Checkbox
              Checkbox(
                value: session.isCompleted,
                activeColor: AppColors.success,
                shape: RoundedRectangleBorder(
                  borderRadius: BorderRadius.circular(4),
                ),
                onChanged: (_) {
                  ref
                      .read(plannerControllerProvider.notifier)
                      .toggleComplete(session);
                },
              ),
              const SizedBox(width: 8),

              // Content
              Expanded(
                child: Column(
                  crossAxisAlignment: CrossAxisAlignment.start,
                  children: [
                    Row(
                      children: [
                        // Time Pill
                        Container(
                          padding: const EdgeInsets.symmetric(
                            horizontal: 8,
                            vertical: 3,
                          ),
                          decoration: BoxDecoration(
                            color:
                                (session.isBreak
                                        ? AppColors.warning
                                        : AppColors.primary)
                                    .withValues(alpha: 0.12),
                            borderRadius: BorderRadius.circular(6),
                          ),
                          child: Text(
                            '${session.startTime} - ${session.endTime}',
                            style: TextStyle(
                              fontSize: 11,
                              fontWeight: FontWeight.w700,
                              color: session.isBreak
                                  ? AppColors.warning
                                  : AppColors.primary,
                            ),
                          ),
                        ),
                        const SizedBox(width: 6),

                        // Priority Badge
                        if (!session.isBreak)
                          Container(
                            padding: const EdgeInsets.symmetric(
                              horizontal: 6,
                              vertical: 3,
                            ),
                            decoration: BoxDecoration(
                              color: priorityColor.withValues(alpha: 0.12),
                              borderRadius: BorderRadius.circular(6),
                            ),
                            child: Text(
                              session.priority.toUpperCase(),
                              style: TextStyle(
                                fontSize: 9.5,
                                fontWeight: FontWeight.w800,
                                color: priorityColor,
                              ),
                            ),
                          ),
                        const Spacer(),

                        // Duration
                        Text(
                          '${session.durationMinutes}m',
                          style: TextStyle(
                            fontSize: 12,
                            fontWeight: FontWeight.w600,
                            color: isDark
                                ? AppColors.textMutedDark
                                : AppColors.textSecondaryLight,
                          ),
                        ),
                      ],
                    ),
                    const SizedBox(height: 8),

                    // Subject & Topic
                    Text(
                      session.subject,
                      style: GoogleFonts.inter(
                        fontSize: 15,
                        fontWeight: FontWeight.w700,
                        decoration: session.isCompleted
                            ? TextDecoration.lineThrough
                            : null,
                        color: session.isCompleted
                            ? (isDark
                                  ? AppColors.textMutedDark
                                  : AppColors.textMutedLight)
                            : (isDark
                                  ? AppColors.textPrimaryDark
                                  : AppColors.textPrimaryLight),
                      ),
                    ),
                    if (session.topic.isNotEmpty) ...[
                      const SizedBox(height: 2),
                      Text(
                        session.topic,
                        style: TextStyle(
                          fontSize: 13,
                          color: isDark
                              ? AppColors.textSecondaryDark
                              : AppColors.textSecondaryLight,
                        ),
                      ),
                    ],
                    if (session.notes.isNotEmpty) ...[
                      const SizedBox(height: 6),
                      Text(
                        '💡 ${session.notes}',
                        style: TextStyle(
                          fontSize: 11.5,
                          fontStyle: FontStyle.italic,
                          color: isDark
                              ? AppColors.textMutedDark
                              : AppColors.textMutedLight,
                        ),
                      ),
                    ],
                  ],
                ),
              ),
            ],
          ),
        ),
      ),
    );
  }

  Color _getPriorityColor(String p) {
    switch (p.toLowerCase()) {
      case 'urgent':
        return AppColors.error;
      case 'high':
        return Colors.orange;
      case 'medium':
        return AppColors.primary;
      default:
        return AppColors.secondary;
    }
  }

  Widget _buildEmptyState(bool isDark) {
    return Center(
      child: Padding(
        padding: const EdgeInsets.all(32),
        child: Column(
          mainAxisAlignment: MainAxisAlignment.center,
          children: [
            Container(
              padding: const EdgeInsets.all(20),
              decoration: BoxDecoration(
                color: AppColors.primary.withValues(alpha: 0.1),
                shape: BoxShape.circle,
              ),
              child: const Icon(
                Icons.calendar_today_rounded,
                size: 48,
                color: AppColors.primary,
              ),
            ),
            const SizedBox(height: 18),
            Text(
              'No Study Sessions for this day',
              style: GoogleFonts.inter(
                fontSize: 18,
                fontWeight: FontWeight.w700,
                color: isDark
                    ? AppColors.textPrimaryDark
                    : AppColors.textPrimaryLight,
              ),
            ),
            const SizedBox(height: 8),
            Text(
              'Add your customized sessions manually, or let StudyMate auto-generate a smart plan based on your exams.',
              textAlign: TextAlign.center,
              style: TextStyle(
                fontSize: 13.5,
                color: isDark
                    ? AppColors.textSecondaryDark
                    : AppColors.textSecondaryLight,
              ),
            ),
            const SizedBox(height: 20),
            AppButton(
              text: 'Auto-Generate Schedule',
              icon: Icons.auto_awesome_rounded,
              variant: AppButtonVariant.primary,
              onPressed: () => _showAutoGenerateDialog(context),
            ),
          ],
        ),
      ),
    );
  }

  void _showAddSessionSheet(BuildContext context) {
    final subjectCtrl = TextEditingController();
    final topicCtrl = TextEditingController();
    final startCtrl = TextEditingController(text: '09:00');
    final endCtrl = TextEditingController(text: '10:00');
    final notesCtrl = TextEditingController();
    String priority = 'medium';
    bool isBreak = false;

    showModalBottomSheet(
      context: context,
      isScrollControlled: true,
      backgroundColor: Colors.transparent,
      builder: (ctx) {
        return StatefulBuilder(
          builder: (context, setSheetState) {
            final isDark = Theme.of(context).brightness == Brightness.dark;
            return Container(
              padding: EdgeInsets.only(
                top: 20,
                left: 20,
                right: 20,
                bottom: MediaQuery.of(context).viewInsets.bottom + 20,
              ),
              decoration: BoxDecoration(
                color: isDark ? AppColors.surfaceDark : AppColors.surfaceLight,
                borderRadius: const BorderRadius.vertical(
                  top: Radius.circular(20),
                ),
              ),
              child: SingleChildScrollView(
                child: Column(
                  mainAxisSize: MainAxisSize.min,
                  crossAxisAlignment: CrossAxisAlignment.start,
                  children: [
                    Center(
                      child: Container(
                        width: 40,
                        height: 4,
                        decoration: BoxDecoration(
                          color: Colors.grey.withValues(alpha: 0.4),
                          borderRadius: BorderRadius.circular(2),
                        ),
                      ),
                    ),
                    const SizedBox(height: 16),
                    Text(
                      'Add Study Session',
                      style: GoogleFonts.inter(
                        fontSize: 18,
                        fontWeight: FontWeight.w700,
                      ),
                    ),
                    const SizedBox(height: 16),

                    AppTextField(
                      controller: subjectCtrl,
                      label: 'Subject',
                      hint: 'e.g. Mathematics, Physics',
                    ),
                    const SizedBox(height: 12),

                    AppTextField(
                      controller: topicCtrl,
                      label: 'Topic / Chapter',
                      hint: 'e.g. Calculus & Derivatives',
                    ),
                    const SizedBox(height: 12),

                    Row(
                      children: [
                        Expanded(
                          child: AppTextField(
                            controller: startCtrl,
                            label: 'Start Time',
                            hint: '09:00',
                          ),
                        ),
                        const SizedBox(width: 12),
                        Expanded(
                          child: AppTextField(
                            controller: endCtrl,
                            label: 'End Time',
                            hint: '10:30',
                          ),
                        ),
                      ],
                    ),
                    const SizedBox(height: 12),

                    // Priority Selector
                    Row(
                      children: ['low', 'medium', 'high', 'urgent'].map((p) {
                        final isSel = priority == p;
                        return Expanded(
                          child: GestureDetector(
                            onTap: () => setSheetState(() => priority = p),
                            child: Container(
                              margin: const EdgeInsets.symmetric(horizontal: 3),
                              padding: const EdgeInsets.symmetric(vertical: 8),
                              decoration: BoxDecoration(
                                color: isSel
                                    ? AppColors.primary
                                    : Colors.transparent,
                                borderRadius: BorderRadius.circular(8),
                                border: Border.all(
                                  color: isSel
                                      ? AppColors.primary
                                      : AppColors.borderLight,
                                ),
                              ),
                              alignment: Alignment.center,
                              child: Text(
                                p.toUpperCase(),
                                style: TextStyle(
                                  fontSize: 10,
                                  fontWeight: FontWeight.w700,
                                  color: isSel
                                      ? Colors.white
                                      : AppColors.textSecondaryLight,
                                ),
                              ),
                            ),
                          ),
                        );
                      }).toList(),
                    ),
                    const SizedBox(height: 12),

                    Row(
                      children: [
                        Checkbox(
                          value: isBreak,
                          activeColor: AppColors.warning,
                          onChanged: (v) =>
                              setSheetState(() => isBreak = v ?? false),
                        ),
                        const Text(
                          'Mark as Relaxation / Break Slot',
                          style: TextStyle(fontSize: 13),
                        ),
                      ],
                    ),
                    const SizedBox(height: 12),

                    AppTextField(
                      controller: notesCtrl,
                      label: 'Notes / Target',
                      hint: 'e.g. Solve 10 previous year questions',
                    ),
                    const SizedBox(height: 20),

                    AppButton(
                      width: double.infinity,
                      text: 'Schedule Session',
                      onPressed: () async {
                        if (subjectCtrl.text.trim().isEmpty) return;
                        await ref
                            .read(plannerControllerProvider.notifier)
                            .addSession(
                              subject: subjectCtrl.text.trim(),
                              topic: topicCtrl.text.trim(),
                              sessionDate: _selectedDate,
                              startTime: startCtrl.text.trim(),
                              endTime: endCtrl.text.trim(),
                              durationMinutes: 60,
                              priority: priority,
                              isBreak: isBreak,
                              notes: notesCtrl.text.trim(),
                            );
                        if (ctx.mounted) Navigator.pop(ctx);
                      },
                    ),
                  ],
                ),
              ),
            );
          },
        );
      },
    );
  }

  void _showAutoGenerateDialog(BuildContext context) {
    showDialog(
      context: context,
      builder: (ctx) {
        return AlertDialog(
          title: Row(
            children: [
              const Icon(Icons.auto_awesome_rounded, color: AppColors.primary),
              const SizedBox(width: 8),
              Text(
                'Smart Auto-Planner',
                style: GoogleFonts.inter(fontWeight: FontWeight.w700),
              ),
            ],
          ),
          content: const Text(
            'StudyMate will analyze your upcoming exams and syllabus to automatically distribute 90-minute study sessions and rest breaks across the next 7 days without schedule conflicts.\n\nWould you like to generate this study plan now?',
            style: TextStyle(fontSize: 13.5, height: 1.4),
          ),
          actions: [
            TextButton(
              onPressed: () => Navigator.pop(ctx),
              child: const Text('Cancel'),
            ),
            ElevatedButton(
              style: ElevatedButton.styleFrom(
                backgroundColor: AppColors.primary,
              ),
              onPressed: () async {
                Navigator.pop(ctx);
                final count = await ref
                    .read(plannerControllerProvider.notifier)
                    .autoGenerateSchedule(
                      startDate: DateTime.now(),
                      dailyStudyHours: 4,
                      sessionLengthMinutes: 90,
                    );
                if (mounted && context.mounted) {
                  ScaffoldMessenger.of(context).showSnackBar(
                    SnackBar(
                      content: Text(
                        '✨ Successfully generated $count study sessions across 7 days!',
                      ),
                      backgroundColor: AppColors.primary,
                    ),
                  );
                }
              },
              child: const Text(
                'Generate Plan',
                style: TextStyle(color: Colors.white),
              ),
            ),
          ],
        );
      },
    );
  }
}
